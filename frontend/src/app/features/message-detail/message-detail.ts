import { Component, OnInit, inject, signal } from "@angular/core";
import { DatePipe, DecimalPipe, Location } from "@angular/common";
import { ActivatedRoute, RouterLink } from "@angular/router";
import { FormsModule } from "@angular/forms";
import { ApiService } from "../../core/services/api.service";
import { InboxStateService } from "../../core/services/inbox-state.service";
import { ToastService } from "../../core/services/toast.service";
import { InboxMessage, Draft } from "../../core/models/inbox.models";
import { IntentBadge } from "../../shared/components/intent-badge/intent-badge";
import { ConfirmModal } from "../../shared/components/confirm-modal/confirm-modal";
@Component({
  standalone: true,
  selector: "app-message-detail",
  imports: [DatePipe, DecimalPipe, RouterLink, FormsModule, IntentBadge, ConfirmModal],
  templateUrl: "./message-detail.html",
  styleUrl: "./message-detail.scss",
})
export class MessageDetail implements OnInit {
  private route = inject(ActivatedRoute);
  private api = inject(ApiService);
  private location = inject(Location);
  private toast = inject(ToastService);
  readonly state = inject(InboxStateService);
  readonly message = signal<InboxMessage | null>(null);
  readonly draft = signal<Draft | null>(null);
  readonly body = signal("");
  readonly busy = signal(false);
  readonly notice = signal("");
  readonly gmailConnected = signal(false);
  readonly gmailAccount = signal<string | null>(null);
  readonly confirmSendOpen = signal(false);

  ngOnInit() {
    const id = this.route.snapshot.paramMap.get("id");
    if (id) this.load(id);
    this.checkGmailStatus();
  }

  checkGmailStatus() {
    this.api.getStatus().subscribe({
      next: (s) => {
        this.gmailConnected.set(s.gmail.connected);
        this.gmailAccount.set(s.gmail.account);
      },
      error: () => this.gmailConnected.set(false)
    });
  }
  load(id: string) {
    this.busy.set(true);
    this.api.getMessage(id).subscribe({
      next: (r) => {
        this.message.set(r.message);
        this.draft.set(r.draft);
        this.body.set(r.draft?.body ?? "");
        this.busy.set(false);
      },
      error: () => {
        this.notice.set("Message not found or backend unavailable.");
        this.busy.set(false);
      },
    });
  }
  createDraft() {
    const m = this.message();
    if (!m) return;
    this.busy.set(true);
    this.api.createDraft(m.id).subscribe({
      next: (r) => {
        this.draft.set(r.draft);
        this.body.set(r.draft.body);
        this.state.upsertDraft(r.draft);
        this.busy.set(false);
        this.toast.success("AI suggested draft created. Review before approval.");
      },
      error: () => {
        this.busy.set(false);
        this.toast.error("Could not generate a draft.");
      },
    });
  }
  save() {
    const d = this.draft();
    if (!d) return;
    this.busy.set(true);
    this.api.updateDraft(d.id, this.body()).subscribe({
      next: (r) => {
        this.draft.set(r.draft);
        this.state.upsertDraft(r.draft);
        this.busy.set(false);
        this.toast.success("Draft edits saved.");
      },
      error: () => {
        this.busy.set(false);
        this.toast.error("Draft could not be saved. Only pending drafts can be edited.");
      },
    });
  }
  regenerate() {
    const d = this.draft();
    if (!d) return;
    this.busy.set(true);
    this.api.regenerateDraft(d.id).subscribe({
      next: (r) => {
        this.draft.set(r.draft);
        this.body.set(r.draft.body);
        this.state.upsertDraft(r.draft);
        this.busy.set(false);
        this.toast.success("Draft regenerated by AI.");
      },
      error: () => {
        this.busy.set(false);
        this.toast.error("Draft could not be regenerated.");
      },
    });
  }
  review(action: "approve" | "reject") {
    const d = this.draft();
    if (!d) return;
    this.busy.set(true);
    this.api.reviewDraft(d.id, action).subscribe({
      next: (r) => {
        this.draft.set(r.draft);
        this.state.upsertDraft(r.draft);
        this.busy.set(false);
        if (action === 'approve') {
          this.toast.success("Draft approved by human review.");
        } else {
          this.toast.info("Draft rejected.");
        }
      },
      error: () => {
        this.busy.set(false);
        this.toast.error("Review action failed. It may already have been reviewed.");
      },
    });
  }
  send(): void {
    this.promptSend();
  }

  promptSend() {
    const d = this.draft();
    if (!d || d.status !== "approved") return;
    if (!this.gmailConnected()) {
      this.toast.error("Cannot send email: Gmail is not connected. Please connect your Gmail account in Mailbox Integration first.");
      return;
    }
    this.confirmSendOpen.set(true);
  }

  cancelSend() {
    this.confirmSendOpen.set(false);
  }

  executeSend() {
    const d = this.draft();
    if (!d || d.status !== "approved") return;
    this.busy.set(true);
    this.api.sendDraft(d.id).subscribe({
      next: (r) => {
        this.confirmSendOpen.set(false);
        this.draft.set(r.draft);
        this.state.upsertDraft(r.draft);
        this.busy.set(false);
        this.toast.success(r.note || "Response successfully sent to candidate!");
      },
      error: (err) => {
        this.confirmSendOpen.set(false);
        this.busy.set(false);
        this.toast.error(err.error?.error || "Failed to send response.");
      },
    });
  }
  back() {
    this.location.back();
  }
  copy() {
    navigator.clipboard
      ?.writeText(this.body())
      .then(() => this.toast.success("Draft copied to clipboard."))
      .catch(() => this.toast.error("Clipboard access unavailable."));
  }
}
